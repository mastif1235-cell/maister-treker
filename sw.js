const CACHE_NAME = 'maister-treker-v61'; // NEW: результати незалежного QA (4 аудитори) — 1) номер з кодом країни (+380...) більше не ламає маску телефону (раніше "+380671234567" ставало "(380)671-23-45" замість "(067)123-45-67"); 2) масова правка профілю абонента тепер перебудовує текст заявки й досилає зміни в Google Таблицю (раніше диспетчеру й у хмару йшли старі дані); 3) пошук на головному екрані тепер знаходить заявки за цифрами телефону; 4) номер договору генерується від найбільшого вже виданого сьогодні номера, а не від кількості заявок — видалення заявки посеред дня більше не може призвести до дубля номера; 5) дати щоденного бекапу й місячних Telegram-звітів рахуються за місцевим часом, не UTC (раніше в вузькому вікні після півночі могли вважати "вчорашній" день/місяць); 6) ціна "0", виставлена вручну на обладнання/кабель/роботу, більше не підмінюється ціною з каталогу; 7) сортування "найновіше зверху" виправлено ще в 4 місцях (профілі/квартири/збіги наряду), де лишалось текстове порівняння дат; 8) бекап заявки в Telegram тепер спочатку відправляє нову версію і лише після підтвердженого успіху видаляє стару — раніше обрив зв'язку між цими кроками міг лишити заявку зовсім без бекапу.
const CORE_ASSETS = [
  './',
  './index.html',
  './styles.css',
  './qrcode.js',
  './app.js',
  './manifest.json',
  './icon-192.png',
  './icon-512.png'
];

self.addEventListener('install', (e) => {
  e.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(CORE_ASSETS))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);

  // Запити до Google Apps Script (синхронізація) НЕ кешуємо —
  // вони завжди мають йти в мережу, щоб дані були актуальні.
  if (url.origin !== self.location.origin) return;
  if (e.request.method !== 'GET') return;

  // NEW: спочатку кеш (миттєво, незалежно від якості звʼязку), мережа —
  // лише у фоні, щоб оновити кеш до наступного запуску. Раніше було
  // навпаки (мережа спочатку, кеш — лише як fallback після невдачі). Це
  // добре працює, коли зв'язку нема ВЗАГАЛІ (fetch падає одразу), але
  // погано — коли сигнал є, та по факту не працює (глухе село, слабкий
  // 3G): fetch() тоді не падає одразу, а довго висить в очікуванні
  // таймауту, перш ніж зрештою впасти й узяти кеш. Через це застосунок
  // міг не відкриватись хвилинами саме там, де інтернет "начебто є" —
  // хоча в кеші вже лежить усе потрібне для миттєвого запуску.
  e.respondWith(
    caches.match(e.request).then((cached) => {
      const networkFetch = fetch(e.request).then((res) => {
        if (res && res.status === 200) {
          const clone = res.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(e.request, clone));
        }
        return res;
      }).catch(() => cached);
      return cached || networkFetch;
    })
  );
});
